"""Calibrated probabilities and conformal prediction sets.

Two tiers, measured in ``privatemode-decisions-benchmark``:

* **No labels.** Raw probabilities from one masked token are overconfident.
  Dividing the log probabilities by a temperature ``T > 1`` fixes most of
  that. :class:`~decisions.SystemOne` applies the benchmark's value by
  default, from the number of options (:data:`FORMULAS`) or, if you name
  the kind of task, from its family (:data:`FAMILY_TEMPERATURES`). It is a
  better starting point, not a guarantee: the best ``T`` varies by task.
* **A few hundred labels.** :func:`calibrate` fits a temperature and a bias
  per option for your task and a conformal cutoff;
  :meth:`Calibration.predict_set` then returns the options that contain the
  right one with the chosen probability, a guarantee that holds on average
  over new inputs drawn like the labelled ones. Label a *random* sample:
  labels collected only from escalated cases are skewed toward hard ones and
  break the guarantee.

A temperature never changes the chosen option, only how sure the answer says
it is. The bias does change answers, which is what makes it gain accuracy:
use :meth:`Calibration.apply`.
"""

